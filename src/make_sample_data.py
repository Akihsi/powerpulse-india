"""Generate SYNTHETIC sample data in the same file layout as the Zenodo dataset.

Purpose: let the team test the whole pipeline (and the dashboard) before/without the real
download. The numbers are invented. They must never appear in the report or presentation.

    python src/make_sample_data.py          # writes data/sample_raw/
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

os.environ["POWERPULSE_MODE"] = "sample"
sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

import config  # noqa: E402

rng = np.random.default_rng(42)
OUT = config.RAW_DIR
OUT.mkdir(parents=True, exist_ok=True)

dates = pd.date_range("2013-01-01", "2025-03-31", freq="D")
n = len(dates)
doy = dates.dayofyear.values
t_years = (dates - dates[0]).days.values / 365.25
is_weekend = (dates.dayofweek >= 5).astype(float)

# rough scale (MU/day) and climate (mean temp C, seasonal swing C) per state; invented
big = {"Uttar Pradesh": 420, "Maharashtra": 470, "Gujarat": 330, "Tamil Nadu": 300, "Rajasthan": 250,
       "Karnataka": 230, "Andhra Pradesh": 250, "Madhya Pradesh": 220, "Punjab": 190, "Telangana": 200,
       "West Bengal": 150, "Haryana": 180, "Delhi": 100, "Bihar": 110, "Odisha": 100}
states = list(config.REGIONS)
base = {s: big.get(s, float(rng.uniform(1.5, 60))) for s in states}
climate = {s: (float(rng.uniform(15, 29)), float(rng.uniform(4, 11))) for s in states}
climate["Kerala"] = (27.0, 2.0)
climate["Rajasthan"] = (26.0, 9.0)
climate["Himachal Pradesh"] = (14.0, 9.0)
climate["Jammu and Kashmir"] = (11.0, 11.0)
climate["Ladakh"] = (3.0, 13.0)

energy, peak_met, peak_unmet = {}, {}, {}
weather = {}
for s in states:
    mean_t, swing = climate[s]
    seasonal = -np.cos(2 * np.pi * (doy - 20) / 365.25)           # coldest ~20 Jan, hottest ~20 Jul
    tmean = mean_t + swing * 0.8 * seasonal + 2.0 * np.sin(2 * np.pi * (doy - 105) / 365.25) + rng.normal(0, 1.2, n)
    cooling = np.clip(tmean - 24, 0, None)
    growth = 1 + 0.045 * t_years
    e = base[s] * growth * (1 + 0.012 * cooling) * (1 - 0.04 * is_weekend) * (1 + rng.normal(0, 0.02, n))
    e = np.round(e, 1)
    if s == "Andaman and Nicobar Islands":
        e[:900] = np.nan
    if s == "Ladakh":
        e[:1500] = np.nan
    if s == "Telangana":
        e[: (pd.Timestamp("2014-06-02") - dates[0]).days] = np.nan
    energy[s] = e
    pm = e * 1000 / 24 * (1.22 + rng.normal(0, 0.03, n))
    peak_met[s] = np.round(pm, 0)
    um = np.where(rng.random(n) < 0.12, np.abs(rng.normal(0, 0.012, n)) * pm, 0.0)
    peak_unmet[s] = np.round(um, 0)

    kelvin = 273.15
    w = pd.DataFrame({"date": dates.strftime("%Y-%m-%d")})
    w["2m_temperature_min"] = tmean - 5 + kelvin
    w["2m_temperature_mean"] = tmean + kelvin
    w["2m_temperature_max"] = tmean + 6 + kelvin
    w["2m_dewpoint_temperature_min"] = tmean - 10 + kelvin
    w["2m_dewpoint_temperature_mean"] = tmean - 6 + kelvin
    w["2m_dewpoint_temperature_max"] = tmean - 2 + kelvin
    for comp in ("u", "v"):
        for stat, off in (("min", -2.0), ("mean", 0.0), ("max", 2.0)):
            w[f"10m_{comp}_component_of_wind_{stat}"] = off + rng.normal(0, 1, n)
    for stat, mult in (("min", 0.0), ("mean", 0.55), ("max", 1.0)):
        w[f"surface_solar_radiation_downwards_{stat}"] = mult * 2.5e6 * (1 + 0.3 * seasonal * 0.5) * rng.uniform(0.7, 1.0, n)
    for stat, off in (("min", 0.0), ("mean", 0.4), ("max", 0.9)):
        w[f"total_cloud_cover_{stat}"] = np.clip(off + rng.normal(0, 0.15, n), 0, 1)
    for stat, off in (("min", -4.0), ("mean", 0.0), ("max", 5.0)):
        w[f"utci_{stat}"] = tmean + off + 1.5 + kelvin
    weather[s] = w

# --- wide national files -------------------------------------------------------------------
def wide(d: dict, extra_cols: bool = True) -> pd.DataFrame:
    df = pd.DataFrame({"Date": dates.strftime("%Y-%m-%d")})
    for s in sorted(d):
        df[s] = d[s]
    if extra_cols:   # non-state columns that exist in the real grid files; the pipeline must drop them
        df["AMNSIL"] = np.round(rng.uniform(0.5, 1.5, n), 1)
        df["Damodar Valley Corporation"] = np.round(rng.uniform(5, 20, n), 1)
    return df

wide(energy).to_csv(OUT / config.ENERGY_FILE, index=False)
wide(peak_met).to_csv(OUT / config.PEAK_MET_FILE, index=False)
wide(peak_unmet).to_csv(OUT / config.PEAK_UNMET_FILE, index=False)

for s, w in weather.items():
    w.to_csv(OUT / f"{config.stem_from_state(s)}.csv", index=False)

(OUT / "SYNTHETIC.txt").write_text(
    "These files are SYNTHETIC test data generated by src/make_sample_data.py.\n"
    "They are not real measurements. Do not use any number derived from them in the report.\n"
)
print(f"Wrote synthetic sample data for {len(states)} states to {OUT}")
